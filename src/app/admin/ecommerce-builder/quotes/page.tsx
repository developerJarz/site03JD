import type { Metadata } from "next";
import Link from "next/link";
import { Suspense } from "react";
import { ListToolbar } from "@/components/admin/list-toolbar";
import { EmptyState, PageHeader, Pagination, Table, td, th } from "@/components/admin/ui";
import { Badge } from "@/components/ui/badge";
import { requirePermission } from "@/lib/auth/session";
import { connectDB, isDbConfigured } from "@/lib/db/connect";
import { formatMoney } from "@/lib/ecommerce-builder/pricing";
import { escapeRegex, formatDate, formatDateTime } from "@/lib/utils";
import { BuilderInvoice, BuilderQuote } from "@/models/builder";

export const metadata: Metadata = { title: "Quotes & invoices" };

const perPage = 25;

export default async function BuilderQuotesPage({ searchParams }: PageProps<"/admin/ecommerce-builder/quotes">) {
  await requirePermission("builder:orders");
  const crumbs = [{ label: "Dashboard", href: "/admin" }, { label: "E-commerce Builder", href: "/admin/ecommerce-builder" }, { label: "Quotes & invoices" }];
  const header = <PageHeader title="Quotes & invoices" description="Every quotation generated by the builder (estimates), and the invoices issued for confirmed orders." crumbs={crumbs} />;
  if (!isDbConfigured) {
    return (
      <>
        {header}
        <EmptyState title="Connect a database" description="Set MONGODB_URI to store quotations." />
      </>
    );
  }
  const sp = await searchParams;
  const tab = sp.tab === "invoices" ? "invoices" : "quotes";
  const q = typeof sp.q === "string" ? sp.q.slice(0, 80) : "";
  const page = Math.max(1, Number(sp.page ?? 1) || 1);
  const re = q ? new RegExp(escapeRegex(q), "i") : null;
  const now = new Date();

  await connectDB();
  const tabs = (
    <nav aria-label="Records" className="mb-5 flex gap-2">
      {(["quotes", "invoices"] as const).map((t) => (
        <Link key={t} href={`/admin/ecommerce-builder/quotes${t === "invoices" ? "?tab=invoices" : ""}`} className={`rounded-xl border px-4 py-2 text-sm ${tab === t ? "border-ink-900 bg-ink-900 text-white" : "border-mist-200 bg-white text-mist-600"}`}>
          {t === "quotes" ? "Quotations" : "Invoices"}
        </Link>
      ))}
    </nav>
  );
  const makeHref = (p: number) => `/admin/ecommerce-builder/quotes?${new URLSearchParams({ ...(tab === "invoices" ? { tab } : {}), ...(q ? { q } : {}), page: String(p) })}`;

  if (tab === "invoices") {
    const filter = re ? { $or: [{ number: re }, { orderNumber: re }, { "customer.name": re }, { "customer.businessName": re }] } : {};
    const [rows, total] = await Promise.all([BuilderInvoice.find(filter).sort({ createdAt: -1 }).skip((page - 1) * perPage).limit(perPage).lean(), BuilderInvoice.countDocuments(filter)]);
    return (
      <>
        {header}
        {tabs}
        <Suspense>
          <ListToolbar placeholder="Search invoice, order or customer…" />
        </Suspense>
        {rows.length === 0 ? (
          <EmptyState title="No invoices yet" description="Issue an invoice from a confirmed order’s page." />
        ) : (
          <>
            <Table>
              <thead>
                <tr>
                  <th scope="col" className={th}>Invoice</th>
                  <th scope="col" className={th}>Order</th>
                  <th scope="col" className={th}>Customer</th>
                  <th scope="col" className={`${th} text-right`}>Total</th>
                  <th scope="col" className={th}>Status</th>
                  <th scope="col" className={th}>Issued</th>
                  <th scope="col" className={th}>Due</th>
                  <th scope="col" className={th}>
                    <span className="sr-only">PDF</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {rows.map((i) => (
                  <tr key={String(i._id)} className="hover:bg-mist-25">
                    <td className={`${td} font-medium text-ink-900`}>{i.number}</td>
                    <td className={td}>
                      <Link href={`/admin/ecommerce-builder/orders/${i.order}`} className="text-brand-700 hover:underline">
                        {i.orderNumber}
                      </Link>
                    </td>
                    <td className={`${td} text-mist-700`}>{i.customer?.businessName || i.customer?.name}</td>
                    <td className={`${td} text-right tabular-nums`}>{formatMoney(i.total, i.currency ?? "USD")}</td>
                    <td className={td}>
                      <Badge tone={i.status === "void" ? "neutral" : "info"} dot>
                        {i.status === "void" ? "Void" : "Issued"}
                      </Badge>
                    </td>
                    <td className={`${td} whitespace-nowrap text-mist-600`}>{formatDate(i.issuedAt)}</td>
                    <td className={`${td} whitespace-nowrap text-mist-600`}>{i.dueAt ? formatDate(i.dueAt) : "—"}</td>
                    <td className={`${td} text-right`}>
                      <a href={`/api/admin/ecommerce-builder/invoices/${i._id}/pdf`} target="_blank" rel="noopener" className="text-sm font-medium text-brand-700 hover:underline">
                        PDF
                      </a>
                    </td>
                  </tr>
                ))}
              </tbody>
            </Table>
            <Pagination page={page} pages={Math.max(1, Math.ceil(total / perPage))} total={total} makeHref={makeHref} />
          </>
        )}
      </>
    );
  }

  const filter = re ? { $or: [{ number: re }, { templateId: re }, { "customer.name": re }, { "customer.email": re }, { "customer.businessName": re }] } : {};
  const [rows, total] = await Promise.all([
    BuilderQuote.find(filter).sort({ createdAt: -1 }).skip((page - 1) * perPage).limit(perPage).select("number breakdown.template.name breakdown.lines breakdown.custom total currency validUntil order customer pricebookVersion createdAt").lean(),
    BuilderQuote.countDocuments(filter),
  ]);
  return (
    <>
      {header}
      {tabs}
      <Suspense>
        <ListToolbar placeholder="Search quotation no., template or customer…" />
      </Suspense>
      {rows.length === 0 ? (
        <EmptyState title="No quotations yet" description="Quotations appear when visitors generate one or submit an order in the builder." />
      ) : (
        <>
          <Table>
            <thead>
              <tr>
                <th scope="col" className={th}>Quotation</th>
                <th scope="col" className={th}>Template</th>
                <th scope="col" className={th}>Features</th>
                <th scope="col" className={`${th} text-right`}>Total</th>
                <th scope="col" className={th}>Customer</th>
                <th scope="col" className={th}>Status</th>
                <th scope="col" className={th}>Created</th>
                <th scope="col" className={th}>
                  <span className="sr-only">PDF</span>
                </th>
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => {
                const bd = r.breakdown as { template?: { name?: string }; lines?: unknown[]; custom?: unknown[] };
                const expired = new Date(r.validUntil) < now;
                return (
                  <tr key={String(r._id)} className="hover:bg-mist-25">
                    <td className={`${td} whitespace-nowrap font-medium text-ink-900`}>
                      {r.number}
                      <span className="block text-xs font-normal text-mist-500">Pricebook v{r.pricebookVersion}</span>
                    </td>
                    <td className={`${td} text-mist-700`}>{bd.template?.name ?? "—"}</td>
                    <td className={`${td} tabular-nums text-mist-700`}>
                      {bd.lines?.length ?? 0}
                      {bd.custom?.length ? ` + ${bd.custom.length} custom` : ""}
                    </td>
                    <td className={`${td} text-right tabular-nums`}>{formatMoney(r.total, r.currency ?? "USD")}</td>
                    <td className={`${td} text-mist-700`}>{r.customer?.name ? r.customer.businessName || r.customer.name : <span className="text-mist-400">Anonymous</span>}</td>
                    <td className={td}>
                      {r.order ? (
                        <Link href={`/admin/ecommerce-builder/orders/${r.order}`}>
                          <Badge tone="success" dot>
                            Ordered
                          </Badge>
                        </Link>
                      ) : expired ? (
                        <Badge tone="neutral" dot>
                          Expired
                        </Badge>
                      ) : (
                        <Badge tone="info" dot>
                          Open
                        </Badge>
                      )}
                    </td>
                    <td className={`${td} whitespace-nowrap text-mist-600`}>{formatDateTime(r.createdAt)}</td>
                    <td className={`${td} text-right`}>
                      <a href={`/api/admin/ecommerce-builder/quotes/${r._id}/pdf`} target="_blank" rel="noopener" className="text-sm font-medium text-brand-700 hover:underline">
                        PDF
                      </a>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </Table>
          <Pagination page={page} pages={Math.max(1, Math.ceil(total / perPage))} total={total} makeHref={makeHref} />
        </>
      )}
    </>
  );
}
